//! The abstract-algebra spine: the ring → field tower for **scalar and exact
//! types** (`f64`, `f32`, complex scalars, and finite/exact types like ℤ, ℚ,
//! GF(p)). This is the "*what algebraic structure is this*" layer.
//!
//! It is the companion of [`crate::numeric`]: where `numeric` is the **element-wise,
//! `Clone`-based** numeric interface that a lazy `Tensor` or a columnar `Expr` can
//! also implement, `algebra` is the **`Copy`, `const`-bearing** scalar interface —
//! the properties only an individual number can have (`const ZERO`/`ONE`, a total
//! order for pivoting, `div_rem`). A `Tensor` deliberately does *not* implement
//! these, so the type system keeps lazy array backends out of scalar-only code.
//!
//! These are pure structure: **no linear-algebra kernels live here.** The dense
//! BLAS dispatch (gemm/herk/adjoint products/solves) belongs to `ramanujan`, which
//! binds these traits and adds the matrix operations on top.

use core::ops::{Add, AddAssign, Div, DivAssign, Mul, MulAssign, Neg, Sub, SubAssign};

/// A **semiring**: an additive commutative monoid with a multiplicative monoid and
/// distributivity — addition and multiplication with their identities, but no
/// subtraction. The natural numbers ℕ are the canonical example.
pub trait Semiring:
    Copy + PartialEq + Add<Output = Self> + Mul<Output = Self> + AddAssign + MulAssign
{
    /// The additive identity.
    const ZERO: Self;
    /// The multiplicative identity.
    const ONE: Self;
}

/// A **ring**: a [`Semiring`] with additive inverses (subtraction and negation).
/// ℤ (`i64`/`i128`) is the canonical non-field ring.
pub trait Ring: Semiring + Sub<Output = Self> + Neg<Output = Self> + SubAssign {}

/// Marker: a [`Ring`] whose multiplication commutes (`a·b = b·a`). Named so generic
/// code can require it explicitly.
pub trait CommutativeRing: Ring {}

/// Marker: a [`CommutativeRing`] with no zero divisors (`a·b = 0 ⇒ a = 0 ∨ b = 0`),
/// so cancellation holds. ℤ and every field qualify; ℤ/nℤ for composite `n` does not.
pub trait IntegralDomain: CommutativeRing {}

/// Marker: a **unique factorization domain** — every element factors into
/// irreducibles uniquely (up to units/order), so gcds exist.
pub trait Ufd: IntegralDomain {}

/// Marker: a **principal ideal domain** — every ideal is generated by one element.
pub trait Pid: Ufd {}

/// A **Euclidean domain**: a [`Pid`] with division-with-remainder. `div_rem` is the
/// defining operation — the exact-division primitive that fraction-free algorithms
/// build on, generalizing integer division beyond ℤ to any Euclidean domain.
pub trait EuclideanDomain: Pid {
    /// The quotient and remainder of `self ÷ rhs`. For a field the remainder is
    /// always [`ZERO`](Semiring::ZERO); for ℤ it is the usual integer division and
    /// modulus.
    fn div_rem(self, rhs: Self) -> (Self, Self);
}

/// A **field**: every nonzero element is invertible (division is total away from
/// `ZERO`), so a field is a (trivial) [`EuclideanDomain`]. The
/// [`conjugate`](Self::conjugate) is the identity for real-like fields (ℝ, ℚ,
/// GF(p)) — writing algorithms against it unifies the real and complex cases, which
/// is exactly what generic adjoint / Hermitian linear algebra needs.
pub trait Field: EuclideanDomain + Div<Output = Self> + DivAssign {
    /// The complex conjugate — the identity for real-like fields.
    fn conjugate(self) -> Self;
}

/// Marker: a [`Field`] with a total order compatible with the operations (ℚ, ℝ — not
/// ℂ, not the finite fields). The structure magnitude-based pivoting relies on.
pub trait OrderedField: Field + PartialOrd {}

/// Marker: a [`Field`] in which every non-constant polynomial has a root (ℂ — not ℝ,
/// not ℚ, not GF(p)). This is what guarantees a matrix's eigenvalues lie in the field.
pub trait AlgebraicallyClosedField: Field {}

// --- f64 / f32: the real ordered fields -----------------------------------

impl Semiring for f64 {
    const ZERO: Self = 0.0;
    const ONE: Self = 1.0;
}
impl Ring for f64 {}
impl CommutativeRing for f64 {}
impl IntegralDomain for f64 {}
impl Ufd for f64 {}
impl Pid for f64 {}
impl EuclideanDomain for f64 {
    fn div_rem(self, rhs: Self) -> (Self, Self) {
        (self / rhs, 0.0)
    }
}
impl Field for f64 {
    fn conjugate(self) -> Self {
        self
    }
}
impl OrderedField for f64 {}

impl Semiring for f32 {
    const ZERO: Self = 0.0;
    const ONE: Self = 1.0;
}
impl Ring for f32 {}
impl CommutativeRing for f32 {}
impl IntegralDomain for f32 {}
impl Ufd for f32 {}
impl Pid for f32 {}
impl EuclideanDomain for f32 {
    fn div_rem(self, rhs: Self) -> (Self, Self) {
        (self / rhs, 0.0)
    }
}
impl Field for f32 {
    fn conjugate(self) -> Self {
        self
    }
}
impl OrderedField for f32 {}

#[cfg(test)]
mod tests {
    use super::*;

    /// A formula written once over any field: `(a·b + 1) / a`, using the structural
    /// identities and operators. Runs on every `Field`.
    fn affine_ratio<T: Field>(a: T, b: T) -> T {
        (a * b + T::ONE) / a
    }

    #[test]
    fn real_fields_satisfy_the_tower() {
        assert_eq!(affine_ratio(2.0_f64, 3.0), (2.0 * 3.0 + 1.0) / 2.0);
        assert_eq!(affine_ratio(2.0_f32, 3.0), (2.0 * 3.0 + 1.0) / 2.0);
        // Real conjugation is the identity.
        assert_eq!(2.5_f64.conjugate(), 2.5);
        // Field division has zero remainder.
        assert_eq!(7.0_f64.div_rem(2.0), (3.5, 0.0));
    }

    #[test]
    fn f64_is_both_an_algebra_field_and_a_euclid_field() {
        // The same primitive type implements the scalar-algebra tower (here) and
        // the element-wise analysis interface (crate::numeric) -- the two euclid
        // families meet on the concrete scalars.
        fn needs_algebra<T: Field>(_: T) {}
        fn needs_analysis<T: crate::numeric::RealScalar>(_: T) {}
        needs_algebra(1.0_f64);
        needs_analysis(1.0_f64);
    }
}
