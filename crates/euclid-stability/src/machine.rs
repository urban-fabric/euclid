//! Sequential properties: a system checked against a model over a *sequence* of operations.
//!
//! Everything else in this crate tests one value at a time. That finds the bugs that live in a
//! function, and it cannot find the bugs that live in a **sequence** — a cache that returns a
//! stale entry only after an eviction, a key tree that collides only after a split and a fold, a
//! factor cache that is correct until something invalidates it. Those are bugs in the
//! *interleaving*, and no single-shot property can express one.
//!
//! The shape is the standard one. A **model** is a simplified reimplementation that is obviously
//! correct because it is slow and does nothing clever; the **system** is the real thing. Generate
//! a sequence of commands, apply each to both, and require that the real thing agrees with the
//! obvious thing at every step. The model is the oracle, which is what lets this work on code
//! with no closed-form answer to compare against.
//!
//! # Why a tape makes this nearly free
//!
//! This is the part worth understanding, because it is where the choice-tape design pays off
//! most and it is the thing other frameworks have to engineer around.
//!
//! Shrinking a command sequence means deleting commands. Delete one and the sequence usually
//! becomes **illegal**: popping an empty stack, reading a key that was never written, committing
//! a transaction that was never opened. So a framework holding a stored list of commands has to
//! detect that and repair it — proptest-state-machine filters invalid sequences and Hypothesis
//! re-runs rules against preconditions, and both can spend a lot of effort discarding candidates,
//! which is exactly the regime where shrinking stalls.
//!
//! Here, the commands after a deletion are not replayed. They are **re-derived**: the generator
//! reads the tape under the model state that now exists, because [`Machine::command`] takes the
//! model and the tape is a sequence of choices rather than of values. Delete the push and the
//! draw that used to produce "pop" reads the same tape entries against an empty model and
//! produces whatever that model offers instead. Every candidate is a legal sequence by
//! construction, so there is nothing to filter and no repair step to get wrong.
//!
//! That is the same property that makes dependent generators work elsewhere in this crate, and a
//! command sequence is the most dependent generator there is — every command's legal set is a
//! function of every command before it.
//!
//! # What it cannot do
//!
//! A command may depend on the **model**, never on what the system returned. The sequence is
//! generated by running the model alone, which is what keeps it a pure function of the tape — and
//! therefore shrinkable, persistable as a tape, and replayable. So "write a key, then read back
//! whatever the write returned" is not expressible; "write a key the model says exists, then read
//! it" is. In practice that covers the stateful bugs worth hunting, and the restriction is what
//! buys the shrinking above.
//!
//! # Example
//!
//! ```
//! use euclid_stability::machine::{Machine, check_machine};
//! use euclid_stability::{Config, Failure, Gen, Outcome, generate};
//!
//! /// A counter that saturates at a ceiling — the system under test.
//! struct Saturating {
//!     value: u32,
//! }
//!
//! /// `Clone` because `generate::just` hands out copies of a fixed value; `Debug` because a
//! /// command sequence is the counterexample a failure report has to show.
//! #[derive(Debug, Clone)]
//! enum Op {
//!     Add(u32),
//!     Reset,
//! }
//!
//! struct CounterMachine;
//!
//! impl Machine for CounterMachine {
//!     type System = Saturating;
//!     /// The model is just the ceiling arithmetic, written the obvious way.
//!     type Model = u32;
//!     type Command = Op;
//!
//!     fn system() -> Self::System {
//!         Saturating { value: 0 }
//!     }
//!     fn model() -> Self::Model {
//!         0
//!     }
//!
//!     /// Depends on the model: near the ceiling, draw the increments that straddle it.
//!     fn command(model: &Self::Model) -> Gen<Self::Command> {
//!         let headroom = 100u32.saturating_sub(*model);
//!         generate::weighted(vec![
//!             (8, generate::int(0, i64::from(headroom) + 2).map(|v| Op::Add(v as u32))),
//!             (1, generate::just(Op::Reset)),
//!         ])
//!     }
//!
//!     fn step_model(model: &mut Self::Model, command: &Self::Command) {
//!         match command {
//!             Op::Add(by) => *model = (*model + by).min(100),
//!             Op::Reset => *model = 0,
//!         }
//!     }
//!
//!     fn step_system(system: &mut Self::System, model: &Self::Model, command: &Self::Command)
//!         -> Outcome
//!     {
//!         match command {
//!             Op::Add(by) => system.value = (system.value + by).min(100),
//!             Op::Reset => system.value = 0,
//!         }
//!         if system.value == *model {
//!             Ok(())
//!         } else {
//!             Err(Failure::new(
//!                 format!("after {command:?}: system {}, model {model}", system.value),
//!                 "a sequential property",
//!             ))
//!         }
//!     }
//! }
//!
//! check_machine::<CounterMachine>("a_saturating_counter", &Config::default(), 12);
//! ```

use crate::generate::Gen;
use crate::runner::{Config, Outcome, check};

/// A system, a model that is obviously correct, and the commands that drive both.
///
/// Implement this on a marker type rather than on the system itself: the associated types keep
/// the system, the model and the command vocabulary together, and the system usually lives in
/// another crate where this trait cannot be implemented on it directly.
pub trait Machine {
    /// The real thing under test.
    type System;
    /// A simplified reimplementation whose correctness is obvious by inspection. Slow is fine —
    /// it only ever runs over a short command sequence, and being slow is often what makes it
    /// obviously right.
    type Model;
    /// One operation. `Debug` because it is what a failure report and a persisted regression
    /// line show — a sequence of commands is the counterexample a reader has to understand.
    type Command: core::fmt::Debug;

    /// A fresh system.
    fn system() -> Self::System;

    /// A fresh model, in the state corresponding to [`system`](Self::system).
    fn model() -> Self::Model;

    /// The commands legal in this model state.
    ///
    /// **Taking the model is how legality is expressed**, and it is the whole mechanism behind
    /// the shrinking described in the module docs: a generator that cannot produce an illegal
    /// command makes every shrink candidate legal for free. So prefer narrowing the generator to
    /// adding a precondition — "draw an index within the current length" rather than "draw any
    /// index and skip the out-of-range ones", which would reject most candidates while shrinking.
    ///
    /// It is also the place to weight towards the interesting region, exactly as a value
    /// generator would: near a boundary, draw the operations that straddle it.
    fn command(model: &Self::Model) -> Gen<Self::Command>;

    /// Advance the model.
    ///
    /// Called during *generation* as well as execution — that is how the next command's generator
    /// sees the state its predecessors produced — so this must be pure with respect to anything
    /// outside the model. Touching the system from here would make the sequence depend on the
    /// system and stop it being a function of the tape.
    fn step_model(model: &mut Self::Model, command: &Self::Command);

    /// Apply the command to the system and check it against the model.
    ///
    /// `model` has **already advanced**, so it describes the state the system is expected to be
    /// in after `command`. That ordering is deliberate: the usual question is "does the system now
    /// agree with the model", and having to remember to advance the model yourself is the kind of
    /// detail that makes a model-based test quietly check the wrong state.
    fn step_system(
        system: &mut Self::System,
        model: &Self::Model,
        command: &Self::Command,
    ) -> Outcome;

    /// Checked after every step, for claims that are not about any single command.
    ///
    /// Anything that must hold throughout — a size that never exceeds a capacity, an index that
    /// stays in bounds, a sum that stays conserved. The default holds vacuously, because a
    /// machine whose per-step check is complete does not need one.
    fn invariant(_system: &Self::System, _model: &Self::Model) -> Outcome {
        Ok(())
    }
}

/// A generator of **legal** command sequences for `M`, up to `max_steps` long.
///
/// The length is drawn first, so lowering that one tape entry shortens the sequence and the
/// shrinker gets sequence minimisation the same way it gets list minimisation — see
/// [`generate::vec`](crate::generate::vec), which draws its length first for the same reason.
///
/// Only the model runs here. The system is not constructed, which is what makes generation cheap
/// enough to do inside every shrink probe.
pub fn commands<M: Machine + 'static>(max_steps: usize) -> Gen<Vec<M::Command>>
where
    M::Command: 'static,
{
    Gen::new(move |source| {
        #[allow(clippy::cast_possible_wrap)]
        let steps = source.in_range(0, max_steps as i64)?;
        #[allow(clippy::cast_sign_loss)]
        let steps = steps as usize;

        let mut model = M::model();
        let mut sequence = Vec::with_capacity(steps);
        for _ in 0..steps {
            let command = M::command(&model).draw(source)?;
            M::step_model(&mut model, &command);
            sequence.push(command);
        }
        Ok(sequence)
    })
}

/// Run `sequence` against a fresh system and model, checking at every step.
///
/// Public because a caller with a sequence in hand — from a persisted regression, or a
/// hand-written case worth pinning — may want to run it without going through a search.
pub fn execute<M: Machine>(sequence: &[M::Command]) -> Outcome {
    let mut system = M::system();
    let mut model = M::model();

    M::invariant(&system, &model)?;
    for command in sequence {
        M::step_model(&mut model, command);
        M::step_system(&mut system, &model, command)?;
        M::invariant(&system, &model)?;
    }
    Ok(())
}

/// Search for a command sequence on which `M`'s system disagrees with its model.
///
/// A thin composition of [`commands`] and [`execute`] over the ordinary [`check`], which is the
/// point: a sequential property is a property whose generated value happens to be a command
/// sequence, so it inherits **everything** the engine already does. Shrinking minimises the
/// sequence, [`Config::regressions`] persists it as a replayable tape with the command list
/// rendered beside it, [`crate::stats`] classifies it, and a [`budget`](crate::budget) baseline
/// works if the property reports a score. None of that needed a second runner.
///
/// # Panics
/// If the property fails, or if every case was rejected.
pub fn check_machine<M: Machine + 'static>(name: &str, config: &Config, max_steps: usize)
where
    M::Command: 'static,
{
    check(name, config, &commands::<M>(max_steps), |sequence| {
        execute::<M>(&sequence)
    });
}

